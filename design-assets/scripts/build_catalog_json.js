// Add file sizes from disk
assets.forEach(asset => {
  const fullPath = path.join(ROOT, asset.file);
  if (fs.existsSync(fullPath)) {
    const stat = fs.statSync(fullPath);
    asset.sizeBytes = stat.size;
    if (stat.size >= 1024 * 1024) {
      asset.sizeFormatted = `${(stat.size / (1024 * 1024)).toFixed(2)} MB`;
    } else if (stat.size >= 1024) {
      asset.sizeFormatted = `${(stat.size / 1024).toFixed(1)} KB`;
    } else {
      asset.sizeFormatted = `${stat.size} B`;
    }
  } else {
    console.warn(`File missing: ${fullPath}`);
    asset.sizeBytes = 0;
    asset.sizeFormatted = '0 B';
  }
});

const catalog = {
  version: '1.0.0',
  updatedAt: new Date().toISOString(),
  projectName: 'SmartSchedule Design Asset Library',
  summary: {
    totalAssets: assets.length,
    totalSizeBytes: assets.reduce((sum, a) => sum + a.sizeBytes, 0),
    totalSizeFormatted: `${(assets.reduce((sum, a) => sum + a.sizeBytes, 0) / 1024).toFixed(1)} KB`,
    categories: {
      backgrounds: assets.filter(a => a.category === 'backgrounds').length,
      textures: assets.filter(a => a.category === 'textures').length,
      illustrations: assets.filter(a => a.category === 'illustrations').length,
      photography: assets.filter(a => a.category === 'photography').length
    }
  },
  assets
};

const targetPath = path.join(ROOT, 'catalog.json');
fs.writeFileSync(targetPath, JSON.stringify(catalog, null, 2), 'utf8');
console.log(`Successfully generated ${targetPath}`);
console.log(`Summary:`, catalog.summary);
